param([switch]$Apply)

$ErrorActionPreference = 'Stop'
$root = 'D:\Claude Cinematics'
$cs   = Join-Path $root 'cloudstream'

# Only files the pipeline PRODUCED. Upstream-tracked assets inside clones are never touched.
$targets = New-Object System.Collections.ArrayList

# 1. render/shot caches per edit project: edit-workspace\<Title>\cache\...
foreach ($t in (Get-ChildItem (Join-Path $cs 'edit-workspace') -Directory -ErrorAction SilentlyContinue)) {
    $cache = Join-Path $t.FullName 'cache'
    if (Test-Path -LiteralPath $cache) {
        Get-ChildItem -LiteralPath $cache -Recurse -File -Include *.mp4,*.pdf -ErrorAction SilentlyContinue |
            ForEach-Object { [void]$targets.Add($_) }
    }
}

# 2. provider/job caches and probe outputs
foreach ($p in @('data\cache', 'data\intel')) {
    $full = Join-Path $cs $p
    if (Test-Path -LiteralPath $full) {
        Get-ChildItem -LiteralPath $full -Recurse -File -Include *.mp4,*.pdf -ErrorAction SilentlyContinue |
            ForEach-Object { [void]$targets.Add($_) }
    }
}

# 3. generated "video to PDF" sheets (the bridge writes one PDF page per frame)
$pdfRoot = Join-Path $cs 'extensions\youtube\pdfs'
if (Test-Path -LiteralPath $pdfRoot) {
    Get-ChildItem -LiteralPath $pdfRoot -Recurse -File -Include *.pdf -ErrorAction SilentlyContinue |
        ForEach-Object { [void]$targets.Add($_) }
}

$total = ($targets | Measure-Object Length -Sum).Sum
Write-Output ('Candidates: ' + $targets.Count + ' files, ' + ('{0:N1} MB' -f ($total/1MB)))
Write-Output ''

$byArea = $targets | Group-Object {
    if ($_.FullName -match '\\edit-workspace\\') { 'edit-workspace cache' }
    elseif ($_.FullName -match '\\data\\cache\\')  { 'data\cache' }
    elseif ($_.FullName -match '\\data\\intel\\')  { 'data\intel (probe outputs)' }
    elseif ($_.FullName -match '\\pdfs\\')         { 'extensions youtube pdfs (generated)' }
    else { 'other' }
}
foreach ($g in $byArea) {
    Write-Output ('  ' + $g.Name.PadRight(34) + ('{0,4} files  {1,9:N1} MB' -f $g.Count, (($g.Group | Measure-Object Length -Sum).Sum/1MB)))
}

# Manifest is written before deletion, so the record survives even if something fails.
$manifest = Join-Path $cs 'data\DELETED-MEDIA-LOG.txt'
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('# Produced mp4/pdf removed on ' + (Get-Date -Format 'yyyy-MM-dd HH:mm'))
$lines.Add('# All of it is regenerated by the bridge; see AGENTS.md "Rebuild from zero".')
$lines.Add('# Upstream-tracked assets inside skills\ and extensions\ clones were NOT touched.')
$lines.Add('')
foreach ($f in ($targets | Sort-Object FullName)) {
    $lines.Add(('{0,10:N1} MB  {1}' -f ($f.Length/1MB), $f.FullName.Replace($root + '\', '')))
}
$lines.Add('')
$lines.Add('TOTAL: ' + $targets.Count + ' files, ' + ('{0:N1} MB' -f ($total/1MB)))

if (-not $Apply) {
    Write-Output ''
    Write-Output 'DRY RUN. Re-run with -Apply to delete. Manifest preview:'
    Write-Output ('  would write ' + $manifest)
    $byArea | Out-Null
    exit 0
}

$lines | Set-Content -LiteralPath $manifest -Encoding UTF8

$ok = 0; $fail = 0
foreach ($f in $targets) {
    try { Remove-Item -LiteralPath $f.FullName -Force; $ok++ }
    catch { $fail++; Write-Output ('FAILED: ' + $f.FullName + ' :: ' + $_.Exception.Message) }
}
Write-Output ''
Write-Output ('Deleted ' + $ok + ' files, ' + $fail + ' failures.')
Write-Output ('Manifest: ' + $manifest)
